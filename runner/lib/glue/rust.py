"""Rust glue: `src/main.rs`, `src/mi_json.rs` and `src/mi_types.rs` beside the engineer's `src/solution.rs`.

Types: int -> i64, float -> f64, string -> String, T[] -> Vec<T>, T? -> Option<T>, [A, B] -> (A, B),
{string: T} -> HashMap<String, T>, records -> structs (an optional key is an Option, None when absent),
unions -> enums (int | string -> IntOrString with variants Int and Str). Names keep the pack's snake_case; a
class gets `new` and `&mut self` methods. The JSON reader in mi_json.rs keeps the project free of dependencies.
"""
import os

from . import Unsupported, all_types, named_types, walk
from ..signature import fmt

KEYWORDS = {"as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for", "if",
            "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "self", "Self",
            "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where", "while", "async",
            "await", "dyn", "abstract", "become", "box", "do", "final", "macro", "override", "priv", "typeof",
            "unsized", "virtual", "yield", "try", "gen"}
SCALAR_RS = {"int": "i64", "float": "f64", "bool": "bool", "string": "String"}
VARIANT = {"int": "Int", "float": "Float", "bool": "Bool", "string": "Str", "list": "List", "tuple": "Tuple",
           "map": "Map"}
JSON_KIND = {"int": "int", "float": "float", "bool": "bool", "string": "string", "list": "array",
             "tuple": "array", "map": "object", "record": "object"}
MAX_TUPLE = 4
JSON_SUPPORT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "mi_json.rs")


def ident(name):
    if name in ("self", "Self", "super", "crate"):
        return name + "_"
    return "r#" + name if name in KEYWORDS else name


def _uname(t):
    return {"int": "Int", "float": "Float", "bool": "Bool", "string": "String"}.get(t[0], VARIANT.get(t[0], "Record"))


class Rust:
    file = "src/main.rs"

    def check(self, sig):
        for t, _ctx in all_types(sig):
            if t[0] == "tuple" and len(t[1]) > MAX_TUPLE:
                raise Unsupported("Rust glue supports tuples of up to %d items (%s)" % (MAX_TUPLE, fmt(t)))
            if t[0] == "union":
                kinds = []
                for m in t[1]:
                    if m[0] in ("opt", "union"):
                        raise Unsupported("write a nullable union as (A | B)? (%s)" % fmt(t))
                    kinds.append(JSON_KIND[m[0]])
                if len(set(kinds)) < len(kinds):
                    raise Unsupported("a union needs members of different JSON kinds (%s)" % fmt(t))
            if t[0] == "record":
                for name, optional, ft in t[1]:
                    if optional and ft[0] == "opt":
                        raise Unsupported("Rust cannot tell an absent field from a null one (%s?: %s)"
                                          % (name, fmt(ft)))

    def _setup(self, sig):
        self.check(sig)
        self.names = named_types(sig, ("record", "union"),
                                 structural=lambda t: "Or".join(_uname(m) for m in t[1]) if t[0] == "union"
                                 else None, reserved=(sig.name,))

    def rt(self, t):
        tag = t[0]
        if tag in SCALAR_RS:
            return SCALAR_RS[tag]
        if tag == "list":
            return "Vec<%s>" % self.rt(t[1])
        if tag == "opt":
            return "Option<%s>" % self.rt(t[1])
        if tag == "tuple":
            return "(%s)" % ", ".join(self.rt(m) for m in t[1])
        if tag == "map":
            return "HashMap<String, %s>" % self.rt(t[1])
        return self.names[fmt(t)]

    def _has_union(self, t):
        found = []
        walk(t, "", lambda x, _c: found.append(x[0] == "union"))
        return any(found)

    def _types_file(self, sig, pack_id):
        out = ["// Code generated by mockinterview for %s. DO NOT EDIT: the runner rewrites it on every run.\n"
               "#![allow(dead_code, unused_imports)]\n\nuse crate::mi_json::*;\nuse std::collections::HashMap;\n"
               % pack_id]
        seen = set()
        for t, _ctx in all_types(sig):
            key = fmt(t)
            if t[0] not in ("record", "union") or key in seen:
                continue
            seen.add(key)
            name = self.names[key]
            if t[0] == "record":
                derive = "Debug, Clone, PartialEq" + ("" if self._has_union(t) else ", Default")
                fields = "".join("    pub %s: %s,\n" % (ident(n), "Option<%s>" % self.rt(ft) if o else self.rt(ft))
                                 for n, o, ft in t[1])
                dec = "".join(
                    ("            %s: if v.has(\"%s\") { Some(FromJson::from_json(v.get(\"%s\"))) } else { None },\n"
                     % (ident(n), n, n)) if o else
                    "            %s: FromJson::from_json(v.get(\"%s\")),\n" % (ident(n), n) for n, o, _ft in t[1])
                enc = "".join(
                    ("        if let Some(x) = &self.%s {\n            out.push((\"%s\".to_string(), x.to_json()));\n"
                     "        }\n" % (ident(n), n)) if o else
                    "        out.push((\"%s\".to_string(), self.%s.to_json()));\n" % (n, ident(n))
                    for n, o, _ft in t[1])
                optional = any(o for _n, o, _t in t[1])
                out.append("/// `%s`%s\n#[derive(%s)]\npub struct %s {\n%s}\n\n"
                           "impl FromJson for %s {\n    fn from_json(v: &Json) -> Self {\n        %s {\n%s        }\n"
                           "    }\n}\n\nimpl ToJson for %s {\n    fn to_json(&self) -> Json {\n"
                           "        let mut out = Vec::new();\n%s        Json::Obj(out)\n    }\n}\n"
                           % (key, " (None: the key is absent)" if optional else "", derive, name, fields,
                              name, name, dec, name, enc))
            else:
                members = t[1]
                kinds = [JSON_KIND[m[0]] for m in members]
                variants = [(self.names[fmt(m)] if m[0] == "record" else VARIANT[m[0]], m) for m in members]
                decl = "".join("    %s(%s),\n" % (v, self.rt(m)) for v, m in variants)
                arms = []
                for (v, m), k in zip(variants, kinds):
                    pat = {"int": "Json::Int(_)", "float": "Json::Float(_)", "bool": "Json::Bool(_)",
                           "string": "Json::Str(_)", "array": "Json::Arr(_)", "object": "Json::Obj(_)"}[k]
                    if k == "float" and "int" not in kinds:
                        pat = "Json::Float(_) | Json::Int(_)"
                    arms.append("            %s => %s::%s(FromJson::from_json(v)),\n" % (pat, name, v))
                enc = "".join("            %s::%s(x) => x.to_json(),\n" % (name, v) for v, _m in variants)
                out.append("/// `%s`\n#[derive(Debug, Clone, PartialEq)]\npub enum %s {\n%s}\n\n"
                           "impl FromJson for %s {\n    fn from_json(v: &Json) -> Self {\n        match v {\n%s"
                           "            other => panic!(\"mockinterview: expected %s, got {:?}\", other),\n"
                           "        }\n    }\n}\n\nimpl ToJson for %s {\n    fn to_json(&self) -> Json {\n"
                           "        match self {\n%s        }\n    }\n}\n"
                           % (key, name, decl, name, "".join(arms), key, name, enc))
        return "\n".join(out)

    def _params(self, decl):
        return ", ".join("%s: %s" % (ident(n), self.rt(t)) for n, t in decl.params)

    def _ret(self, decl):
        return "" if decl.returns == ("void",) else " -> " + self.rt(decl.returns)

    def stub(self, sig, kind):
        self._setup(sig)
        head = ""
        if self.names:
            head += "#[allow(unused_imports)]\nuse crate::mi_types::*; // %s\n" % ", ".join(sorted(self.names.values()))
        if any(t[0] == "map" for t, _c in all_types(sig)):
            head += "use std::collections::HashMap;\n"
        head += "\n" if head else ""
        if kind == "func":
            return head + "pub fn %s(%s)%s {\n    todo!()\n}\n" % (ident(sig.name), self._params(sig), self._ret(sig))
        methods = ["    pub fn new(%s) -> Self {\n        %s {}\n    }\n" % (self._params(sig), sig.name)]
        for m in sig.methods:
            params = self._params(m)
            methods.append("    pub fn %s(&mut self%s)%s {\n        todo!()\n    }\n"
                           % (ident(m.name), ", " + params if params else "", self._ret(m)))
        return head + "pub struct %s {\n}\n\nimpl %s {\n%s}\n" % (sig.name, sig.name, "\n".join(methods))

    def files(self, sig, kind, pack_id, request_name):
        self._setup(sig)

        def args(decl, var):
            return ", ".join("FromJson::from_json(&%s[%d])" % (var, i) for i in range(len(decl.params)))

        if kind == "func":
            call = ("    let a = req.get(\"args\").arr();\n    %s(%s).to_json()\n" % (ident(sig.name), args(sig, "a")))
        else:
            arms = "".join("            \"%s\" => obj.%s(%s).to_json(),\n" % (request_name(m.name), ident(m.name),
                                                                              args(m, "a"))
                           for m in sig.methods)
            call = ("    let calls = req.get(\"calls\").arr();\n    let first = calls[0].arr()[1].arr();\n"
                    "    let mut obj = %s::new(%s);\n    let mut out = vec![Json::Null];\n"
                    "    for c in &calls[1..] {\n        let c = c.arr();\n        let a = c[1].arr();\n"
                    "        let name = match &c[0] {\n            Json::Str(s) => s.as_str(),\n"
                    "            _ => \"\",\n        };\n        out.push(match name {\n%s"
                    "            other => panic!(\"unknown method {}\", other),\n        });\n    }\n"
                    "    Json::Arr(out)\n" % (sig.name, args(sig, "first"), arms))
        main = ("// Code generated by mockinterview for %s. DO NOT EDIT: the runner rewrites it on every run.\n"
                "mod mi_json;\nmod mi_types;\nmod solution;\n\nuse mi_json::*;\n#[allow(unused_imports)]\n"
                "use mi_types::*;\nuse solution::*;\n\n#[allow(unused_variables, unused_mut)]\n"
                "fn mi_call(req: &Json) -> Json {\n%s}\n\n"
                "fn main() {\n    let path = std::env::args().nth(1).expect(\"usage: mi_solution RESULT_FILE\");\n"
                "    let mut input = String::new();\n"
                "    std::io::Read::read_to_string(&mut std::io::stdin(), &mut input).expect(\"cannot read stdin\");\n"
                "    let worker = std::thread::Builder::new()\n        .stack_size(1 << 28)\n"
                "        .spawn(move || {\n"
                "            let req = parse(&input).unwrap_or_else(|e| panic!(\"mockinterview: bad request: {}\", e));\n"
                "            mi_call(&req).dump()\n        })\n        .expect(\"cannot start a thread\");\n"
                "    match worker.join() {\n"
                "        Ok(text) => std::fs::write(&path, text).expect(\"cannot write the result\"),\n"
                "        Err(_) => std::process::exit(1), // the panic message is already on stderr\n    }\n}\n"
                % (pack_id, call))
        with open(JSON_SUPPORT, encoding="utf-8") as fh:
            support = fh.read()
        return {"src/main.rs": main, "src/mi_json.rs": support, "src/mi_types.rs": self._types_file(sig, pack_id)}
